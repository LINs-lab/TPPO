def prompt_text(tokenizer, prompt) -> str:
    messages = prompt if isinstance(prompt, list) else [{"role": "user", "content": str(prompt)}]
    return tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)


def load_distcp_head(path: Path):
    """Read output_layer directly from a Megatron torch-dist checkpoint."""
    import torch
    import torch.distributed.checkpoint as dcp

    metadata = dcp.FileSystemReader(str(path)).read_metadata()
    entries = metadata.state_dict_metadata

    def find(suffix):
        matches = [key for key in entries if key == suffix or key.endswith("." + suffix)]
        if not matches:
            raise KeyError(f"{suffix} not found in {path}")
        return min(matches, key=len)

    weight_key = find("output_layer.weight")
    bias_key = find("output_layer.bias")
    weight_meta = entries[weight_key]
    bias_meta = entries[bias_key]
    weight = torch.empty(tuple(weight_meta.size), dtype=weight_meta.properties.dtype)
    bias = torch.empty(tuple(bias_meta.size), dtype=bias_meta.properties.dtype)
    dcp.load({weight_key: weight, bias_key: bias}, checkpoint_id=str(path))
    print(f"Loaded {weight_key} and {bias_key} from {path}")
    return weight, bias


def load_output_layer(critic_path: Path, explicit: Path | None, hidden: int, device, dtype):
    """Load the critic checkpoint's output_layer into an equivalent module."""
    from torch import nn

    source = explicit
    if source is None and (critic_path / ".metadata").is_file():
        weight, bias = load_distcp_head(critic_path)
    else:
        if source is None and critic_path.is_dir():
            for name in ("critic_head.pt", "value_head.pt", "output_layer.pt", "critic_head.safetensors",
                         "model.safetensors", "pytorch_model.bin"):
                candidate = critic_path / name
                if candidate.is_file():
                    source = candidate
                    break
        if source is None:
            raise FileNotFoundError(
                f"No critic output_layer found for {critic_path}; pass head in pairs.jsonl or --head")
        state = load_state(source)
        weight = pick(state, ("output_layer.weight", "value_head.weight", "critic_head.weight", "score.weight", "lm_head.weight", "weight"))
        bias = pick(state, ("output_layer.bias", "value_head.bias", "critic_head.bias", "score.bias", "lm_head.bias", "bias"))
        if weight is None or bias is None:
            raise ValueError(f"{source} must contain output_layer weight and bias")

    dim = int(weight.shape[0])
    if tuple(weight.shape[1:]) != (hidden,) or tuple(bias.shape) != (dim,):
        raise ValueError(f"critic head shape mismatch: got {tuple(weight.shape)}, {tuple(bias.shape)}, expected (*, {hidden})")
    head = nn.Linear(hidden, dim, bias=True, device=device, dtype=dtype)
    head.weight.data.copy_(weight.to(device=device, dtype=dtype))
    head.bias.data.copy_(bias.to(device=device, dtype=dtype))
    head.eval()
    return head


def pick(state: dict[str, torch.Tensor], names: tuple[str, ...]):
    for name in names:
        for key, value in state.items():
            if key == name or key.endswith("." + name):
                return value
    return None


def load_state(path: Path) -> dict[str, torch.Tensor]:
    import torch

    if path.suffix == ".safetensors":
        from safetensors.torch import load_file
        return load_file(str(path), device="cpu")
    value = torch.load(path, map_location="cpu", weights_only=True)
    return value.get("state_dict", value)


def hf_weights_complete(path: Path) -> bool:
    """Check that a converted HF directory has every referenced weight file."""
    if not (path / "config.json").is_file():
        return False
    for name in ("model.safetensors", "pytorch_model.bin"):
        candidate = path / name
        if candidate.is_file() and candidate.stat().st_size > 0:
            return True
    index_path = path / "model.safetensors.index.json"
    if not index_path.is_file() or index_path.stat().st_size == 0:
        return False
    try:
        index = json.loads(index_path.read_text(encoding="utf-8"))
        weight_files = set(index.get("weight_map", {}).values())
    except (OSError, json.JSONDecodeError, AttributeError):
        return False
    return bool(weight_files) and all(
        (path / name).is_file() and (path / name).stat().st_size > 0
        for name in weight_files
    )


def to_hf(
    path: Path,
    out: Path,
    role: str,
    cfg: argparse.Namespace,
    train_tp: int,
) -> tuple[Path, bool]:
    if (path / "config.json").is_file():
        return path, False
    target = out / "hf" / role
    if target.exists():
        if hf_weights_complete(target):
            return target, False
        print(f"Removing incomplete HF {role} directory before reconversion: {target}", flush=True)
        if target.is_dir():
            shutil.rmtree(target)
        else:
            target.unlink()
    if cfg.no_convert:
        raise FileNotFoundError(f"Megatron checkpoint needs conversion: {path}")
    shard_ids = {
        match.group(1)
        for p in path.glob("__*_*.distcp")
        if (match := re.match(r"^__([0-9]+)_", p.name))
    }
    shard_count = len(shard_ids)
    if shard_count != train_tp:
        raise ValueError(f"{path}: found {shard_count} TP shards, expected {train_tp}")
    tool = (Path(__file__).resolve().parents[2] / "slime") / "tools/convert_torch_dist_to_hf_bridge.py"
    target.parent.mkdir(parents=True, exist_ok=True)
    target_existed = target.exists()
    try:
        subprocess.run([
            sys.executable, str(tool), "--input-dir", str(path),
            "--output-dir", str(target), "--origin-hf-dir", str(cfg.origin_hf),
        ], check=True)
    except Exception:
        # Do not leave a partially converted directory when this invocation
        # created it.  A pre-existing directory is left untouched.
        if not target_existed and target.exists():
            shutil.rmtree(target)
        raise
    return target, True


def cleanup_generated_hf(paths: list[Path], cfg: argparse.Namespace) -> None:
    if cfg.keep_generated_hf:
        return
    for path in reversed(paths):
        if not path.is_dir():
            continue
        resolved = path.resolve()
        # The caller only records paths returned as newly created by to_hf;
        # keep an additional scope check before the recursive removal.
        if resolved.parent.name != "hf" or resolved.parent.parent.parent != cfg.out.resolve():
            raise RuntimeError(f"refusing to clean unexpected generated HF path: {path}")
        print(f"Removing temporary generated HF directory: {resolved}")
        shutil.rmtree(resolved)


def values(raw: torch.Tensor, mode: str) -> torch.Tensor:
    import torch

    if mode not in {"tppo"}:
        return raw
    anchor = raw[:1]
    return torch.sigmoid(torch.cat((anchor, anchor + torch.cumsum(raw[1:], dim=0))))


def separate_v0_values(raw: torch.Tensor) -> torch.Tensor:
    """Reconstruct training-aligned values from [v0_logit, delta_logit]."""
    import torch

    if raw.ndim != 2 or raw.shape[-1] != 2:
        raise ValueError(f"separate-v0 critic expects [tokens, 2], got {tuple(raw.shape)}")
    v0_logit = raw[:1, 0]
    delta_logits = raw[1:, 1]
    value_logits = torch.cat((v0_logit, v0_logit + torch.cumsum(delta_logits, dim=0)))
    return torch.sigmoid(value_logits)


def output_token_ids(output: dict, tokenizer) -> list[int]:
    """Get exact generated ids from SGLang; only fall back to retokenization if unavailable."""
    entries = (output.get("meta_info") or {}).get("output_token_logprobs")
    if entries:
        ids = []
        for entry in entries:
            if isinstance(entry, dict):
                token_id = entry.get("token_id")
            elif isinstance(entry, (list, tuple)) and len(entry) > 1:
                token_id = entry[1]
            else:
                token_id = None
            if token_id is not None:
                ids.append(int(token_id))
        if ids:
            return ids
    return tokenizer.encode(output.get("text", ""), add_special_tokens=False)


class SGLangServer:
    def __init__(self, model: Path, cfg: argparse.Namespace):
        self.model = model
        self.cfg = cfg
        self.port = cfg.sglang_port
        self.url = cfg.sglang_url or f"http://{cfg.sglang_host}:{cfg.sglang_port}"
        self.process = None
        self.log_file = None
        self.log_path = self.cfg.sglang_log_path or (model.parent.parent / "sglang_server.log")

    def start(self):
        if self.cfg.sglang_url:
            self._wait()
            return
        # Probe immediately before launch; another process can still claim the
        # port after this socket closes and before SGLang binds it.
        try:
            with socket.create_server((self.cfg.sglang_host, self.port)) as probe:
                self.port = probe.getsockname()[1]
        except OSError as exc:
            if exc.errno != errno.EADDRINUSE:
                raise
            requested_port = self.port
            with socket.create_server((self.cfg.sglang_host, 0)) as probe:
                self.port = probe.getsockname()[1]
            print(
                f"SGLang port {requested_port} is already in use; "
                f"using available port {self.port}", flush=True,
            )
        self.url = f"http://{self.cfg.sglang_host}:{self.port}"
        cmd = [
            sys.executable, "-m", "sglang.launch_server",
            "--model-path", str(self.model),
            "--host", self.cfg.sglang_host,
            "--port", str(self.port),
            "--tp-size", str(self.cfg.actor_tp),
            "--mem-fraction-static", str(self.cfg.sglang_mem_fraction_static),
            "--cuda-graph-bs", "1", "2", "4", "8",
            *map(str, range(16, 257, 8)),
            "--trust-remote-code",
        ]
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        self.log_file = self.log_path.open("w")
        print(f"Starting SGLang for {self.model} at {self.url}; log: {self.log_path}", flush=True)
        # SGLANG_PORT is our shell wrapper's HTTP port setting, but SGLang
        # also reads it in get_open_port() when choosing internal ports.
        # Pass HTTP configuration only through --port to avoid that collision.
        server_env = os.environ.copy()
        server_env.pop("SGLANG_PORT", None)
        self.process = subprocess.Popen(
            cmd, stdout=self.log_file, stderr=subprocess.STDOUT, text=True,
            start_new_session=True, env=server_env,
        )
        self._wait()

    def _wait(self):
        health = f"{self.url}/health_generate"
        for _ in range(300):
            if self.process is not None:
                # Binding can fail while SGLang is still waiting for warmup.
                # Report it immediately instead of waiting for that timeout.
                with self.log_path.open("rb") as log:
                    log.seek(0, os.SEEK_END)
                    log.seek(max(0, log.tell() - 16384))
                    tail = log.read().decode("utf-8", errors="replace")
                for line in tail.splitlines():
                    if "error while attempting to bind" in line and "address already in use" in line:
                        raise RuntimeError(f"SGLang startup failed: {line.strip()}; see {self.log_path}")
            try:
                with urllib.request.urlopen(health, timeout=2) as response:
                    if response.status == 200:
                        return
            except Exception:
                if self.process is not None and self.process.poll() is not None:
                    raise RuntimeError(
                        f"SGLang server exited before becoming healthy "
                        f"(returncode={self.process.returncode}); see {self.log_path}"
                    )
                time.sleep(2)
        raise TimeoutError(f"SGLang server did not become healthy: {health}")

    def stop(self):
        try:
            if self.process is None:
                return
            # The server and its TP workers share the session created in start().
            # Clean workers even when the launcher has already exited.
            try:
                os.killpg(self.process.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
            try:
                self.process.wait(timeout=30)
            except subprocess.TimeoutExpired:
                pass
            finally:
                # A launcher can exit before its workers, including workers
                # that ignore SIGTERM. Do not leave those behind for the next model.
                try:
                    os.killpg(self.process.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
                self.process.wait()
                self.process = None
        finally:
            if self.log_file is not None:
                self.log_file.close()
                self.log_file = None


async def _sglang_generate(client, url, prompt_ids, cfg, response_id, max_new_tokens=None, seed_id=None):
    sampling_params = {
        "temperature": cfg.temperature,
        "top_p": cfg.top_p,
        "top_k": cfg.top_k,
        "max_new_tokens": cfg.max_new_tokens if max_new_tokens is None else max_new_tokens,
        "skip_special_tokens": False,
        "no_stop_trim": True,
        "spaces_between_special_tokens": False,
    }
    if cfg.sglang_deterministic:
        sampling_params["sampling_seed"] = cfg.sglang_seed + (response_id if seed_id is None else seed_id)
    async with cfg.request_semaphore:
        response = await client.post(
            f"{url}/generate",
            json={"input_ids": prompt_ids, "sampling_params": sampling_params, "return_logprob": True},
        )
        response.raise_for_status()
        return response.json()


async def _rollout_async(pair, rows, tokenizer, cfg, existing=None):
    import httpx

    existing = existing or []
    existing_keys = {checkpoint_key(item) for item in existing}
    prompts = [tokenizer.encode(prompt_text(tokenizer, row["prompt"]), add_special_tokens=False) for row in rows]
    requests = [
        (local_prompt_id, cfg.prompt_offset + local_prompt_id, response_id, prompt_ids)
        for local_prompt_id, prompt_ids in enumerate(prompts)
        for response_id in range(cfg.rollouts)
        if (cfg.prompt_offset + local_prompt_id, response_id) not in existing_keys
    ]
    timeout = httpx.Timeout(cfg.sglang_request_timeout, connect=30.0)
    async with httpx.AsyncClient(timeout=timeout, limits=httpx.Limits(max_connections=cfg.sglang_concurrency)) as client:
        outputs = await asyncio.gather(*[
            _sglang_generate(client, cfg.sglang_server.url, prompt_ids, cfg, response_id,
                             seed_id=prompt_id * cfg.rollouts + response_id)
            for _, prompt_id, response_id, prompt_ids in requests
        ])
    data = []
    for (local_prompt_id, prompt_id, response_id, prompt_ids), output in zip(requests, outputs, strict=True):
        data.append({
            "prompt_id": prompt_id,
            "response_id": response_id,
            "local_response_id": response_id,
            "prompt": rows[local_prompt_id]["prompt"],
            "label": rows[local_prompt_id].get("label"),
            "question": rows[local_prompt_id].get("question", rows[local_prompt_id].get("metadata", {}).get("question")),
            "points": rows[local_prompt_id].get("metadata", {}).get("points"),
            "response": output["text"],
            "_prompt_ids": prompt_ids,
            "_response_token_ids": output_token_ids(output, tokenizer),
        })
    return sorted(existing + data, key=checkpoint_key)


def reward_one(item: dict, response: str, cfg: argparse.Namespace) -> dict:
    from slime.rollout.rm_hub.p1 import compute_score_p1

    label = item.get("label")
    labels = label if isinstance(label, list) else [label]
    points = item.get("points")
    if not isinstance(points, list) or not all(isinstance(x, (int, float)) for x in points):
        points = None
    return compute_score_p1(
        response, labels, points=points,
        question=item.get("question") or "",
        use_xverify=cfg.train_use_xverify,
        base_url=cfg.rm_url,
    )


class RewardWorkerTimeout(TimeoutError):
    """A reward worker did not return before its hard deadline."""


class RewardWorkerCrashed(RuntimeError):
    """A reward worker exited before returning a result."""


def _reward_payload(item: dict, cfg: argparse.Namespace) -> dict:
    label = item.get("label")
    labels = label if isinstance(label, list) else [label]
    points = item.get("points")
    if not isinstance(points, list) or not all(isinstance(x, (int, float)) for x in points):
        points = None
    return {
        "labels": labels,
        "points": points,
        "question": item.get("question") or "",
        "use_xverify": bool(cfg.train_use_xverify),
        "base_url": cfg.rm_url,
    }


def _reward_worker_main(conn) -> None:
    """Run reward calls in a process that the parent can forcibly terminate."""
    # Reward scoring is CPU/network work.  Prevent a worker from reserving a
    # visible GPU or inheriting a CUDA context from the rollout process.
    os.environ["CUDA_VISIBLE_DEVICES"] = ""
    try:
        from slime.rollout.rm_hub.p1 import compute_score_p1
    except BaseException as exc:
        try:
            conn.send({"kind": "fatal", "error": repr(exc)})
        finally:
            conn.close()
        return

    try:
        conn.send({"kind": "ready"})
        while True:
            try:
                request = conn.recv()
            except EOFError:
                break
            if request.get("kind") == "stop":
                break
            payload = request["payload"]
            try:
                result = compute_score_p1(
                    request["response"],
                    payload["labels"],
                    points=payload["points"],
                    question=payload["question"],
                    use_xverify=payload["use_xverify"],
                    base_url=payload["base_url"],
                )
                conn.send({
                    "kind": "result",
                    "ok": True,
                    "reward": result,
                })
            except BaseException as exc:
                # A bad response is a failed sample, not a reason to kill the
                # worker.  Only the parent-side deadline kills the process.
                conn.send({"kind": "result", "ok": False, "error": repr(exc)})
    finally:
        conn.close()


class KillableRewardWorker:
    """One isolated reward process with a hard, parent-enforced timeout."""

    def __init__(self):
        context = mp.get_context("spawn")
        self.parent_conn, child_conn = context.Pipe(duplex=True)
        self.process = context.Process(target=_reward_worker_main, args=(child_conn,))
        self.process.daemon = True
        self.process.start()
        child_conn.close()

    async def score(self, payload: dict, response: str, timeout: float):
        try:
            self.parent_conn.send({
                "kind": "score",
                "payload": payload,
                "response": response,
            })
        except (BrokenPipeError, EOFError, OSError) as exc:
            raise RewardWorkerCrashed(repr(exc)) from exc

        deadline = time.monotonic() + float(timeout)
        while True:
            try:
                if self.parent_conn.poll():
                    message = self.parent_conn.recv()
                    kind = message.get("kind")
                    if kind == "ready":
                        continue
                    if kind == "fatal":
                        raise RewardWorkerCrashed(message.get("error", "worker import failed"))
                    if kind != "result":
                        raise RewardWorkerCrashed(f"unexpected worker message: {message!r}")
                    if message.get("ok"):
                        return message["reward"]
                    raise RuntimeError(message.get("error", "reward calculation failed"))
            except (EOFError, OSError, ValueError) as exc:
                raise RewardWorkerCrashed(repr(exc)) from exc
            if not self.process.is_alive():
                raise RewardWorkerCrashed(
                    f"reward worker exited with code {self.process.exitcode}"
                )
            if time.monotonic() >= deadline:
                self.kill()
                raise RewardWorkerTimeout(f"reward worker exceeded {timeout:g}s")
            await asyncio.sleep(0.02)

    def kill(self) -> None:
        if self.process.is_alive():
            self.process.terminate()
            self.process.join(timeout=5)
        if self.process.is_alive():
            self.process.kill()
            self.process.join()
        try:
            self.parent_conn.close()
        except (OSError, ValueError):
            pass

    def close(self) -> None:
        if self.process.is_alive():
            try:
                self.parent_conn.send({"kind": "stop"})
                self.process.join(timeout=5)
            except (BrokenPipeError, EOFError, OSError):
                pass
        if self.process.is_alive():
            self.kill()
        else:
            try:
                self.parent_conn.close()
            except (OSError, ValueError):
                pass


class KillableRewardPool:
    """Bounded pool that replaces a worker immediately after a hard timeout."""

    def __init__(self, cfg: argparse.Namespace):
        self.cfg = cfg
        self.available: asyncio.Queue[KillableRewardWorker] = asyncio.Queue()
        self.workers: list[KillableRewardWorker] = []
        self.closed = False

    async def start(self):
        worker_count = max(
            1,
            min(
                int(getattr(self.cfg, "reward_process_concurrency", 16)),
                int(self.cfg.mc_reward_concurrency),
            ),
        )
        for _ in range(worker_count):
            worker = KillableRewardWorker()
            self.workers.append(worker)
            await self.available.put(worker)
        return self

    async def score(self, item: dict, response: str):
        worker = await self.available.get()
        replace = False
        try:
            return await worker.score(
                _reward_payload(item, self.cfg),
                response,
                self.cfg.reward_timeout,
            )
        except (RewardWorkerTimeout, RewardWorkerCrashed):
            replace = True
            worker.kill()
            raise
        finally:
            if replace:
                if not self.closed:
                    replacement = KillableRewardWorker()
                    self.workers.append(replacement)
                    await self.available.put(replacement)
            elif not self.closed:
                await self.available.put(worker)

    async def close(self) -> None:
        self.closed = True
        for worker in self.workers:
            worker.close()


async def _mc_one(
    client,
    item: dict,
    tokenizer,
    cfg: argparse.Namespace,
    reward_pool: KillableRewardPool,
    item_id: int,
) -> None:
    response_ids = item.get("_response_token_ids", [])
    if not response_ids or cfg.mc_samples <= 0:
        item["mc"] = []
        return

    anchors = []
    response_len = len(response_ids)
    seen_positions = set()
    for ratio_id, ratio in enumerate(cfg.mc_ratios):
        ratio = float(ratio)
        if not 0.0 < ratio < 1.0:
            raise ValueError(f"MC ratios must be in (0, 1), got {ratio}")
        # Keep this identical to slime.rollout.mc_value_label:
        # value position p is the state after p response tokens, and the
        # response has value positions [0, response_len - 1].  The MC prefix
        # therefore contains exactly p response tokens.
        position = _mc_anchor_position(response_len, ratio) if response_len > 1 else 0
        if position in seen_positions:
            continue
        seen_positions.add(position)
        prefix_len = position
        prefix_ids = item["_prompt_ids"] + response_ids[:prefix_len]
        prefix_text = tokenizer.decode(response_ids[:prefix_len], skip_special_tokens=False)
        max_new_tokens = max(1, cfg.max_new_tokens - prefix_len)
        local_response_id = int(item.get("local_response_id", item["response_id"]))
        global_sample_index = int(item["prompt_id"]) * cfg.rollouts + local_response_id
        outputs = await asyncio.gather(*[
            _sglang_generate(
                client, cfg.sglang_server.url, prefix_ids, cfg, sample_id,
                max_new_tokens=max_new_tokens,
                seed_id=1000000 + global_sample_index * len(cfg.mc_ratios) * cfg.mc_samples
                + ratio_id * cfg.mc_samples + sample_id,
            )
            for sample_id in range(cfg.mc_samples)
        ], return_exceptions=True)

        valid_outputs = [output for output in outputs if not isinstance(output, BaseException)]
        score_results = await asyncio.gather(*(
            reward_pool.score(item, prefix_text + output.get("text", ""))
            for output in valid_outputs
        ), return_exceptions=True)
        scores = []
        correct = 0
        failed_samples = sum(1 for output in outputs if isinstance(output, BaseException))
        for result in score_results:
            if isinstance(result, BaseException):
                print(
                    f"WARNING: reward worker failed or timed out for "
                    f"prompt={item.get('prompt_id')} response={item.get('response_id')}: {result!r}",
                    flush=True,
                )
                failed_samples += 1
                continue
            score, acc = float(result["score"]), bool(result["acc"])
            scores.append(score)
            correct += int(acc)
        mean = sum(scores) / len(scores) if scores else 0.0
        variance = (
            sum((score - mean) ** 2 for score in scores) / len(scores)
            if scores else 0.0
        )
        anchors.append({
            "position": position,
            "value_position": position,
            "ratio": ratio,
            "prefix_response_len": prefix_len,
            "max_new_tokens": max_new_tokens,
            "mc_n": len(scores),
            "mc_failed_samples": failed_samples,
            "mc_attempted_samples": cfg.mc_samples,
            "mc_mean": mean,
            "mc_std": math.sqrt(variance),
            "mc_accuracy": correct / len(scores) if scores else 0.0,
        })
    item["mc"] = anchors
    item["anchors"] = anchors


async def _rollout_and_mc_async(pair, rows, tokenizer, cfg, existing=None):
    import httpx

    existing = existing or []
    existing_keys = {checkpoint_key(item) for item in existing}
    data = await _rollout_async(pair, rows, tokenizer, cfg, existing=existing)
    # Persist actor responses before starting MC.  This allows a restart to
    # resume MC without regenerating already completed actor rollouts.
    newly_generated = [item for item in data if checkpoint_key(item) not in existing_keys]
    append_checkpoint(cfg.checkpoint_path, newly_generated)
    if cfg.mc_samples <= 0:
        return data
    timeout = httpx.Timeout(cfg.sglang_request_timeout, connect=30.0)
    reward_pool = await KillableRewardPool(cfg).start()
    try:
        async with httpx.AsyncClient(timeout=timeout, limits=httpx.Limits(max_connections=cfg.sglang_concurrency)) as client:
            pending = [item for item in data if not mc_complete(item)]
            batch_size = max(1, int(cfg.checkpoint_batch_size))
            for start in range(0, len(pending), batch_size):
                batch = pending[start:start + batch_size]
                await asyncio.gather(*[
                    _mc_one(client, item, tokenizer, cfg, reward_pool, item_id)
                    for item_id, item in enumerate(batch, start)
                ])
                for item in batch:
                    item["_mc_done"] = True
                # Save MC results before final-reward scoring.  A timed-out
                # reward worker is killed and replaced, so this checkpoint
                # cannot be held indefinitely by a stuck reward call.
                append_checkpoint(cfg.checkpoint_path, batch)
                write_partial_results(
                    cfg.partial_results_path,
                    [item for item in data if mc_complete(item)],
                )
                await add_rewards_async(batch, cfg, reward_pool=reward_pool)
                append_checkpoint(cfg.checkpoint_path, batch)
                write_partial_results(
                    cfg.partial_results_path,
                    [item for item in data if mc_complete(item)],
                )
                print(
                    f"MC checkpoint: {min(start + len(batch), len(pending))}/{len(pending)} pending trajectories processed",
                    flush=True,
                )
    finally:
        await reward_pool.close()
    return data


def rollout(pair: dict, rows: list[dict], cfg: argparse.Namespace, existing=None):
    import torch
    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(pair["actor"], trust_remote_code=True)
    server = SGLangServer(Path(pair["actor"]), cfg)
    try:
        server.start()
        cfg.sglang_server = server
        cfg.request_semaphore = asyncio.Semaphore(cfg.sglang_concurrency)
        data = asyncio.run(_rollout_and_mc_async(pair, rows, tokenizer, cfg, existing=existing))
    finally:
        server.stop()
        del tokenizer
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    return data


async def add_rewards_async(
    data: list[dict],
    cfg: argparse.Namespace,
    reward_pool: KillableRewardPool | None = None,
) -> None:
    """Use isolated reward workers with a hard timeout per item."""
    owns_pool = reward_pool is None
    if owns_pool:
        reward_pool = await KillableRewardPool(cfg).start()

    async def score_item(item):
        if "reward_detail" in item and "reward" in item and "correct" in item:
            return
        try:
            reward = await reward_pool.score(item, item["response"])
            item["reward"] = reward["score"]
            item["correct"] = bool(reward["acc"])
            item["reward_detail"] = reward
            item.pop("_reward_error", None)
        except Exception as exc:
            item["_reward_error"] = repr(exc)
            print(
                f"WARNING: final reward worker failed or timed out for "
                f"prompt={item.get('prompt_id')} response={item.get('response_id')}: {exc!r}",
                flush=True,
            )

    try:
        await asyncio.gather(*(score_item(item) for item in data))
    finally:
        if owns_pool:
            await reward_pool.close()


def add_rewards(data: list[dict], cfg: argparse.Namespace) -> None:
    """Synchronous wrapper for final reward scoring outside an event loop."""
    asyncio.run(add_rewards_async(data, cfg))


def _mc_metadata(item: dict) -> dict:
    """Convert manual MC anchor rows to Slime's dense sparse-label arrays."""
    response_len = int(item["response_len"])
    labels = [0.0] * response_len
    masks = [0] * response_len
    stds = [0.0] * response_len
    ns = [0.0] * response_len
    details = []
    seen_positions = set()
    for anchor in item.get("anchors", []):
        position = int(anchor["position"])
        if not 0 <= position < response_len:
            raise ValueError(
                f"MC anchor position {position} outside response length {response_len}"
            )
        if position in seen_positions:
            raise ValueError(f"duplicate MC anchor position {position}")
        seen_positions.add(position)
        labels[position] = float(anchor["mc_mean"])
        # Match Slime: an anchor with no valid continuation reward is not a
        # usable label and must not enter the anchor-level advantage mask.
        masks[position] = int(int(anchor.get("mc_n", 0)) > 0)
        stds[position] = float(anchor.get("mc_std", 0.0))
        ns[position] = float(anchor.get("mc_n", 0.0))
        details.append(
            {
                "position": position,
                "value_position": position,
                "prefix_response_len": position,
                "ratio": float(anchor["ratio"]),
                "mean": float(anchor["mc_mean"]),
                "std": float(anchor.get("mc_std", 0.0)),
                "n": int(anchor.get("mc_n", 0)),
                "converged": False,
                "rounds": 1,
                "stop_reason": "fixed_samples",
                "attempted_samples": int(anchor.get(
                    "mc_attempted_samples", anchor.get("mc_n", 0))),
                "failed_samples": int(anchor.get("mc_failed_samples", 0)),
            }
        )
    valid_details = [item for item in details if item["n"] > 0]
    return {
        "mc_value_labels": labels,
        "mc_value_label_masks": masks,
        "mc_value_stds": stds,
        "mc_value_ns": ns,
        "mc_value_anchors": details,
        "mc_value_std_mean": (
            sum(item["std"] for item in valid_details) / len(valid_details)
            if valid_details else 0.0
        ),
        "mc_value_n_mean": (
            sum(item["n"] for item in valid_details) / len(valid_details)
            if valid_details else 0.0
        ),
        "mc_value_converged_mean": 0.0,
        "mc_value_rounds_mean": float(len(details)) if details else 0.0,
        "mc_value_attempted_samples_mean": (
            sum(item["attempted_samples"] for item in details) / len(details)
            if details else 0.0
        ),
        "mc_value_failed_samples_mean": (
            sum(item["failed_samples"] for item in details) / len(details)
            if details else 0.0
        ),
    }


def _mc_anchor_position(response_len: int, ratio: float) -> int:
    """Return the exact response-state index used by Slime MC labels."""
    if response_len <= 0:
        raise ValueError(f"response_len must be positive, got {response_len}")
    if not 0.0 < ratio < 1.0:
        raise ValueError(f"MC ratios must be in (0, 1), got {ratio}")
    return int(round((response_len - 1) * ratio))


def write_slime_rollout(data: list[dict], path: Path) -> None:
    """Write the exact frozen rollout in Slime debug-rollout format.

    Slime's replay loader expects a torch file containing ``samples`` whose
    entries are Sample.to_dict()-compatible dictionaries.  Keeping the exact
    token ids avoids a later response re-tokenization changing the gradient
    alignment.
    """
    import torch

    samples = []
    for item in data:
        response_ids = [int(x) for x in item["_response_token_ids"]]
        prompt_ids = [int(x) for x in item["_prompt_ids"]]
        response_len = len(response_ids)
        if response_len != int(item.get("response_len", response_len)):
            raise ValueError("response_len does not match exact response token ids")
        metadata = dict(_mc_metadata(item))
        metadata["question"] = item.get("question")
        metadata["points"] = item.get("points")
        sample_index = int(item["sample_index"])
        reward = item.get("reward_detail")
        if reward is None:
            raise ValueError(f"missing reward detail for sample {sample_index}")
        samples.append(
            {
                "group_index": int(item["prompt_id"]),
                "index": sample_index,
                "prompt": item["prompt"],
                "tokens": prompt_ids + response_ids,
                "response": item["response"],
                "response_length": response_len,
                "label": item.get("label"),
                "reward": reward,
                "loss_mask": [1] * response_len,
                "status": "completed",
                "metadata": metadata,
            }
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    torch.save({"samples": samples}, path)


def _inference_mode(function):
    try:
        import torch
    except ModuleNotFoundError:
        return function
    return torch.inference_mode()(function)


@_inference_mode
def score(data: list[dict], pair: dict, cfg: argparse.Namespace) -> None:
    import torch
    from transformers import AutoModel, AutoTokenizer

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dtype = torch.bfloat16 if device.type == "cuda" else torch.float32
    tokenizer = AutoTokenizer.from_pretrained(pair["critic"], trust_remote_code=True)
    if tokenizer.pad_token_id is None:
        tokenizer.pad_token = tokenizer.eos_token
    model = AutoModel.from_pretrained(pair["critic"], trust_remote_code=True, torch_dtype=dtype).to(device).eval()
    mode = pair["mode"]
    if mode not in {
        "baseline", "tppo", "tppo_separate_v0_head_logit_bce",
        
    }:
        raise ValueError(f"unknown mode: {mode}")
    hidden_size = getattr(model.config, "hidden_size", getattr(model.config, "n_embd", None))
    if hidden_size is None:
        raise ValueError("critic config has no hidden_size/n_embd")
    model.output_layer = load_output_layer(
        Path(pair.get("critic_source", pair["critic"])),
        Path(pair["head"]) if pair.get("head") else cfg.head,
        int(hidden_size), device, dtype,
    )
    printed_critic_input = False
    pending = [item for item in data if not value_complete(item)]
    for start in range(0, len(pending), cfg.critic_batch_size):
        batch = pending[start:start + cfg.critic_batch_size]
        ids, positions = [], []
        for item in batch:
            text = prompt_text(tokenizer, item["prompt"])
            if cfg.print_critic_input and not printed_critic_input:
                print(text)
                print("===== END CRITIC INPUT =====\n")
                printed_critic_input = True
            prompt_ids = tokenizer.encode(text, add_special_tokens=False)
            # The actor's exact generated ids are the authoritative response
            # sequence.  Re-tokenizing decoded text can change special-token
            # boundaries and would make critic/value positions disagree with
            # the sequence later replayed by Slime.
            response_ids = [int(x) for x in item.get("_response_token_ids", [])]
            if not response_ids:
                response_ids = tokenizer.encode(item["response"], add_special_tokens=False)
            stored_response_len = int(item.get("response_len", len(response_ids)))
            if len(response_ids) != stored_response_len:
                raise ValueError(
                    "response_len does not match the actor response token ids: "
                    f"{stored_response_len} vs {len(response_ids)}"
                )
            ids.append(prompt_ids + response_ids)
            positions.append(list(range(len(prompt_ids) - 1, len(prompt_ids) - 1 + len(response_ids))))
        max_len = max(map(len, ids), default=1)
        input_ids = torch.full((len(ids), max_len), tokenizer.pad_token_id, device=device, dtype=torch.long)
        mask = torch.zeros_like(input_ids)
        for i, token_ids in enumerate(ids):
            input_ids[i, :len(token_ids)] = torch.tensor(token_ids, device=device)
            mask[i, :len(token_ids)] = 1
        hidden = model(input_ids=input_ids, attention_mask=mask).last_hidden_state
        raw = model.output_layer(hidden)
        for i, (item, pos) in enumerate(zip(batch, positions, strict=True)):
            if mode == "tppo_separate_v0_head_logit_bce":
                trace = separate_v0_values(raw[i, pos].float().cpu()).tolist()
            else:
                trace = values(raw[i, pos, 0].float().cpu(), mode).tolist()
            item["value_raw"] = trace
            item["response_len"] = len(trace)
        append_checkpoint(cfg.checkpoint_path, batch)
        write_partial_results(
            cfg.partial_results_path,
            [item for item in data if mc_complete(item)],
        )
    del model, tokenizer
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()


