def read_jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip() and not line.lstrip().startswith("#")]


def checkpoint_key(item: dict) -> tuple[int, int]:
    """Return a stable identity even after response_id is normalized for Slime."""
    local_response_id = item.get("local_response_id", item.get("response_id"))
    return int(item["prompt_id"]), int(local_response_id)


def load_checkpoint(path: Path) -> list[dict]:
    """Load the last valid record for every trajectory.

    If a process is killed while appending one JSON line, the incomplete final
    line is ignored and all earlier completed records remain usable.
    """
    if not path.is_file():
        return []
    latest: dict[tuple[int, int], dict] = {}
    with path.open(encoding="utf-8") as stream:
        for line in stream:
            if not line.strip():
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError:
                break
            if isinstance(item, dict) and "prompt_id" in item and "response_id" in item:
                latest[checkpoint_key(item)] = item
    return [latest[key] for key in sorted(latest)]


def append_checkpoint(path: Path, items: list[dict]) -> None:
    """Append completed trajectory states and force them to disk."""
    if path is None or not items:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as stream:
        for item in items:
            stream.write(json.dumps(item, ensure_ascii=False, separators=(",", ":")) + "\n")
        stream.flush()
        os.fsync(stream.fileno())


def write_partial_results(path: Path, items: list[dict]) -> None:
    """Write a readable snapshot of all MC-completed trajectories so far."""
    if path is None or not items:
        return
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", encoding="utf-8") as stream:
        for item in sorted(items, key=checkpoint_key):
            public = {key: value for key, value in item.items() if not key.startswith("_")}
            stream.write(json.dumps(public, ensure_ascii=False, separators=(",", ":")) + "\n")
        stream.flush()
        os.fsync(stream.fileno())
    temporary.replace(path)


def write_json_atomic(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    temporary.replace(path)


